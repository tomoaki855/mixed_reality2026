#!/usr/bin/env python3
"""
Visualize frame-by-frame squat analysis results and evaluate each repetition.

Input:
    CSV generated by analyze_squat.py

Outputs:
    1. Timeline plot with knee angle, deepest point of each repetition,
       and warning markers.
    2. Per-repetition summary CSV.
    3. Per-repetition depth chart.

Example:
    python scripts/visualize_squat_results.py \
        --input outputs/squat_analysis.csv \
        --timeline outputs/squat_timeline.png \
        --rep-plot outputs/squat_repetitions.png \
        --summary outputs/squat_repetition_summary.csv
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Visualize squat analysis results and score each repetition."
    )
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--timeline", type=Path, required=True)
    parser.add_argument("--rep-plot", type=Path, required=True)
    parser.add_argument("--summary", type=Path, required=True)
    parser.add_argument("--depth-threshold", type=float, default=0.0)
    parser.add_argument("--deep-angle", type=float, default=105.0)
    parser.add_argument("--rounding-threshold", type=float, default=7.0)
    parser.add_argument("--torso-threshold", type=float, default=40.0)
    parser.add_argument("--heel-threshold", type=float, default=0.15)
    parser.add_argument("--toe-threshold", type=float, default=0.85)
    return parser.parse_args()


def require_columns(df: pd.DataFrame, columns: list[str]) -> None:
    missing = [column for column in columns if column not in df.columns]
    if missing:
        raise ValueError(
            "The input CSV is missing required columns: " + ", ".join(missing)
        )


def find_repetition_ranges(df: pd.DataFrame) -> list[tuple[int, int]]:
    phases = df["phase"].fillna("").astype(str).str.upper().to_numpy()
    ranges: list[tuple[int, int]] = []
    start_index: int | None = None

    for index in range(1, len(phases)):
        previous = phases[index - 1]
        current = phases[index]

        if previous == "UP" and current == "DOWN":
            start_index = index
        elif previous == "DOWN" and current == "UP" and start_index is not None:
            ranges.append((start_index, index))
            start_index = None

    return ranges


def finite_max(series: pd.Series) -> float:
    values = pd.to_numeric(series, errors="coerce").to_numpy(dtype=float)
    values = values[np.isfinite(values)]
    return float(np.max(values)) if len(values) else float("nan")


def finite_min(series: pd.Series) -> float:
    values = pd.to_numeric(series, errors="coerce").to_numpy(dtype=float)
    values = values[np.isfinite(values)]
    return float(np.min(values)) if len(values) else float("nan")


def deepest_frame_index(rep_df: pd.DataFrame) -> int:
    depth = pd.to_numeric(rep_df["squat_depth_ratio"], errors="coerce")
    if depth.notna().any():
        return int(depth.idxmax())

    knee = pd.to_numeric(rep_df["knee_angle_deg"], errors="coerce")
    if knee.notna().any():
        return int(knee.idxmin())

    return int(rep_df.index[len(rep_df) // 2])


def summarize_repetitions(
    df: pd.DataFrame,
    repetition_ranges: list[tuple[int, int]],
    args: argparse.Namespace,
) -> pd.DataFrame:
    rows: list[dict] = []

    for repetition_number, (start, end) in enumerate(repetition_ranges, start=1):
        rep_df = df.iloc[start : end + 1]
        deepest_index = deepest_frame_index(rep_df)
        deepest_row = df.loc[deepest_index]

        max_depth_ratio = finite_max(rep_df["squat_depth_ratio"])
        min_knee_angle = finite_min(rep_df["knee_angle_deg"])
        max_torso_lean = finite_max(rep_df["torso_lean_deg"])

        max_upper_back_drop = (
            finite_max(rep_df["upper_back_drop_deg"])
            if "upper_back_drop_deg" in rep_df.columns
            else float("nan")
        )

        min_balance_ratio = (
            finite_min(rep_df["balance_ratio"])
            if "balance_ratio" in rep_df.columns
            else float("nan")
        )
        max_balance_ratio = (
            finite_max(rep_df["balance_ratio"])
            if "balance_ratio" in rep_df.columns
            else float("nan")
        )

        depth_ok = (
            np.isfinite(max_depth_ratio)
            and max_depth_ratio >= args.depth_threshold
        ) or (
            np.isfinite(min_knee_angle)
            and min_knee_angle <= args.deep_angle
        )

        torso_ok = (
            not np.isfinite(max_torso_lean)
            or max_torso_lean <= args.torso_threshold
        )

        upper_back_ok = (
            not np.isfinite(max_upper_back_drop)
            or max_upper_back_drop <= args.rounding_threshold
        )

        balance_ok = True
        if np.isfinite(min_balance_ratio):
            balance_ok = balance_ok and min_balance_ratio >= args.heel_threshold
        if np.isfinite(max_balance_ratio):
            balance_ok = balance_ok and max_balance_ratio <= args.toe_threshold

        errors: list[str] = []
        if not depth_ok:
            errors.append("Shallow squat")
        if not torso_ok:
            errors.append("Excessive torso lean")
        if not upper_back_ok:
            errors.append("Upper-back rounding")
        if not balance_ok:
            errors.append("Foot balance shift")

        overall_ok = depth_ok and torso_ok and upper_back_ok and balance_ok

        rows.append(
            {
                "repetition": repetition_number,
                "start_time_sec": float(rep_df["time_sec"].iloc[0]),
                "end_time_sec": float(rep_df["time_sec"].iloc[-1]),
                "deepest_time_sec": float(deepest_row["time_sec"]),
                "deepest_frame": int(deepest_row["frame"]),
                "max_depth_ratio": max_depth_ratio,
                "min_knee_angle_deg": min_knee_angle,
                "max_torso_lean_deg": max_torso_lean,
                "max_upper_back_drop_deg": max_upper_back_drop,
                "min_balance_ratio": min_balance_ratio,
                "max_balance_ratio": max_balance_ratio,
                "depth_ok": depth_ok,
                "torso_ok": torso_ok,
                "upper_back_ok": upper_back_ok,
                "balance_ok": balance_ok,
                "overall_ok": overall_ok,
                "errors": "; ".join(errors),
            }
        )

    return pd.DataFrame(rows)


def create_timeline_plot(
    df: pd.DataFrame,
    summary: pd.DataFrame,
    output_path: Path,
    deep_angle: float = 105.0,
) -> None:
    """
    スクワットごとのOK/NG区間を背景色で示し，
    最深部とNG理由を吹き出しで表示する．
    """
    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    time = pd.to_numeric(
        df["time_sec"],
        errors="coerce",
    )

    knee = pd.to_numeric(
        df["knee_angle_deg"],
        errors="coerce",
    )

    fig, ax = plt.subplots(
        figsize=(13, 5.5)
    )

    # 膝角度の時系列
    ax.plot(
        time,
        knee,
        linewidth=2.0,
        color="#2369a1",
        label="Knee angle",
        zorder=3,
    )

    # 十分な深さの目安
    ax.axhline(
        deep_angle,
        color="#555555",
        linestyle="--",
        linewidth=1.3,
        alpha=0.8,
        label=f"Depth criterion ({deep_angle:.0f} deg)",
        zorder=1,
    )

    for _, row in summary.iterrows():
        repetition = int(
            row["repetition"]
        )

        start_time = float(
            row["start_time_sec"]
        )

        end_time = float(
            row["end_time_sec"]
        )

        deepest_time = float(
            row["deepest_time_sec"]
        )

        deepest_angle = float(
            row["min_knee_angle_deg"]
        )

        is_ok = bool(
            row["overall_ok"]
        )

        # スクワット区間を背景色で表示
        span_color = (
            "#dff2df"
            if is_ok
            else "#f8dddd"
        )

        point_color = (
            "#238823"
            if is_ok
            else "#cc2222"
        )

        ax.axvspan(
            start_time,
            end_time,
            color=span_color,
            alpha=0.75,
            zorder=0,
        )

        # 最深部
        ax.scatter(
            deepest_time,
            deepest_angle,
            s=100,
            color=point_color,
            edgecolor="white",
            linewidth=1.5,
            zorder=5,
        )

        status = (
            "OK"
            if is_ok
            else "NG"
        )

        # OKは最小限の表示
        if is_ok:
            ax.annotate(
                f"Rep {repetition}\nOK",
                xy=(
                    deepest_time,
                    deepest_angle,
                ),
                xytext=(0, -38),
                textcoords="offset points",
                ha="center",
                va="top",
                fontsize=9,
                color=point_color,
                bbox=dict(
                    boxstyle="round,pad=0.25",
                    facecolor="white",
                    edgecolor=point_color,
                    alpha=0.95,
                ),
            )

        # NGは理由を吹き出し表示
        else:
            errors = str(
                row["errors"]
            )

            error_lines = errors.replace(
                "; ",
                "\n",
            )

            # 吹き出しが重ならないよう左右を交互にする
            horizontal_offset = (
                35
                if repetition % 2 == 0
                else -35
            )

            ax.annotate(
                (
                    f"Rep {repetition}: {status}\n"
                    f"{error_lines}"
                ),
                xy=(
                    deepest_time,
                    deepest_angle,
                ),
                xytext=(
                    horizontal_offset,
                    55,
                ),
                textcoords="offset points",
                ha=(
                    "left"
                    if horizontal_offset > 0
                    else "right"
                ),
                va="bottom",
                fontsize=8.5,
                color="#a00000",
                bbox=dict(
                    boxstyle="round,pad=0.35",
                    facecolor="#fff5f5",
                    edgecolor="#cc2222",
                    alpha=0.97,
                ),
                arrowprops=dict(
                    arrowstyle="->",
                    color="#cc2222",
                    linewidth=1.2,
                    connectionstyle="arc3,rad=0.15",
                ),
                zorder=6,
            )

    ax.set_title(
        "Squat Form Analysis",
        fontsize=16,
    )

    ax.set_xlabel(
        "Time [s]",
        fontsize=12,
    )

    ax.set_ylabel(
        "Knee angle [deg]",
        fontsize=12,
    )

    ax.set_ylim(
        max(
            20,
            float(
                np.nanmin(knee)
            ) - 10,
        ),
        min(
            190,
            float(
                np.nanmax(knee)
            ) + 5,
        ),
    )

    ax.grid(
        True,
        alpha=0.25,
        zorder=0,
    )

    ax.legend(
        loc="upper right",
        frameon=True,
    )

    # 上・右の枠線を消して見やすくする
    ax.spines["top"].set_visible(
        False
    )
    ax.spines["right"].set_visible(
        False
    )

    fig.tight_layout()

    fig.savefig(
        output_path,
        dpi=220,
        bbox_inches="tight",
    )

    plt.close(fig)


def create_repetition_plot(
    summary: pd.DataFrame,
    output_path: Path,
    depth_threshold: float,
) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)

    repetitions = summary["repetition"].astype(int).to_numpy()
    depth_values = summary["max_depth_ratio"].to_numpy(dtype=float)
    colors = [
        "green" if bool(value) else "red"
        for value in summary["overall_ok"]
    ]

    fig, ax = plt.subplots(figsize=(9, 4.5))
    bars = ax.bar(repetitions, depth_values, color=colors)

    ax.axhline(
        depth_threshold,
        linestyle="--",
        linewidth=1.3,
        color="black",
        label="Depth threshold",
    )

    for bar, (_, row) in zip(bars, summary.iterrows()):
        status = "OK" if bool(row["overall_ok"]) else "NG"
        ax.text(
            bar.get_x() + bar.get_width() / 2,
            bar.get_height(),
            status,
            ha="center",
            va="bottom" if bar.get_height() >= 0 else "top",
            color="green" if status == "OK" else "red",
            fontsize=10,
        )

    ax.set_title("Evaluation of each squat repetition")
    ax.set_xlabel("Repetition")
    ax.set_ylabel("Maximum squat depth ratio")
    ax.set_xticks(repetitions)
    ax.grid(True, axis="y", alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(output_path, dpi=200)
    plt.close(fig)


def main() -> None:
    args = parse_args()

    if not args.input.is_file():
        raise FileNotFoundError(f"Input CSV not found: {args.input}")

    df = pd.read_csv(args.input)

    require_columns(
        df,
        [
            "frame",
            "time_sec",
            "phase",
            "knee_angle_deg",
            "torso_lean_deg",
            "squat_depth_ratio",
        ],
    )

    repetition_ranges = find_repetition_ranges(df)
    if not repetition_ranges:
        raise RuntimeError(
            "No complete repetitions were detected. "
            "Check the phase column and UP/DOWN thresholds."
        )

    summary = summarize_repetitions(df, repetition_ranges, args)

    args.summary.parent.mkdir(parents=True, exist_ok=True)
    summary.to_csv(args.summary, index=False, encoding="utf-8")

    create_timeline_plot(df, summary, args.timeline, args.deep_angle)
    create_repetition_plot(summary, args.rep_plot, args.depth_threshold)

    print("Finished.")
    print(f"Timeline plot:      {args.timeline}")
    print(f"Repetition plot:    {args.rep_plot}")
    print(f"Repetition summary: {args.summary}")
    print()
    print(
        summary[
            [
                "repetition",
                "overall_ok",
                "max_depth_ratio",
                "min_knee_angle_deg",
                "errors",
            ]
        ].to_string(index=False)
    )


if __name__ == "__main__":
    main()
